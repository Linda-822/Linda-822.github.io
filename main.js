var lang = 'zh';
function t(key) { return (I18N[lang] && I18N[lang][key]) || ''; }

function applyLang() {
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('.lang-btn').forEach(function (b) {
    b.classList.toggle('active', b.getAttribute('data-lang') === lang);
  });
  route();
}

var VIEWS = ['home', 'about', 'nomi', 'gallery'];
function route() {
  var hash = location.hash.replace(/^#\/?/, '');
  var target = VIEWS.indexOf(hash) !== -1 ? hash : 'home';
  VIEWS.forEach(function (v) {
    var el = document.getElementById('view-' + v);
    el.hidden = v !== target;
  });
  document.querySelectorAll('[data-nav]').forEach(function (a) {
    a.classList.toggle('active', a.getAttribute('data-nav') === target);
  });
  document.title = t('nav.' + target) + ' · 张若琳 | Linda Zhang';
  window.scrollTo(0, 0);
}

document.querySelectorAll('.lang-btn').forEach(function (b) {
  b.addEventListener('click', function () {
    lang = b.getAttribute('data-lang');
    applyLang();
  });
});
window.addEventListener('hashchange', route);
applyLang();
